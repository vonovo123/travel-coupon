export function getDirectAnswer(platformName?: Platform): DirectAnswer {
  if (!platformName) {
    return homeDirectAnswer;
  }

  return platformDirectAnswers[platformName];
}

export function getDirectQuestions(platformName?: Platform): DirectFollowUp[] {
  const answer = getDirectAnswer(platformName);

  return [
    { question: answer.leadQuestion, answer: answer.leadAnswer },
    ...answer.followUps,
  ];
}
